#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
GeneratePostProcessHlsl.py
IrufemiEngine PostProcess HLSL Generator

Parses PostProcessDefinitions.h (C++ Single Source of Truth) and generates
PostProcessModes.generated.hlsli for HLSL shaders to guarantee 1:1 synchronization.
"""

import os
import re
import sys
from pathlib import Path

def parse_post_process_definitions(header_path: Path):
    """
    Parses IRUFEMI_POSTPROCESS_EFFECT_LIST from PostProcessDefinitions.h
    Returns a list of mode names in exact order.
    """
    if not header_path.is_file():
        raise FileNotFoundError(f"Definitions file not found: {header_path}")

    content = header_path.read_text(encoding="utf-8")

    # Match the IRUFEMI_POSTPROCESS_EFFECT_LIST macro block
    pattern = re.compile(
        r"#define\s+IRUFEMI_POSTPROCESS_EFFECT_LIST\s*\(\s*V\s*\)\s*(.*?)(?=\n\s*\n|#define|\Z)",
        re.DOTALL
    )
    match = pattern.search(content)
    if not match:
        raise ValueError("Could not find IRUFEMI_POSTPROCESS_EFFECT_LIST in header.")

    body = match.group(1)

    # Extract each V(ModeName, ...)
    entry_pattern = re.compile(r"V\s*\(\s*([A-Za-z0-9_]+)")
    modes = []
    for line in body.splitlines():
        line = line.strip().rstrip("\\").strip()
        m = entry_pattern.search(line)
        if m:
            modes.append(m.group(1))

    return modes

def generate_hlsl_header(modes: list) -> str:
    """
    Generates the HLSL header content from the list of modes.
    """
    lines = [
        "// -------------------------------------------------------------------------",
        "// THIS FILE IS AUTOMATICALLY GENERATED BY GeneratePostProcessHlsl.py",
        "// DO NOT EDIT MANUALLY! Changes will be overwritten upon build.",
        "// Source: PostProcessDefinitions.h",
        "// -------------------------------------------------------------------------",
        "#pragma once",
        "",
        "// PostProcess Mode Enumeration Constants (Matches C++ enum class PostProcessMode)",
    ]

    for index, mode in enumerate(modes):
        lines.append(f"static const int32_t kPostProcessMode_{mode} = {index};")

    lines.append("")
    lines.append(f"static const int32_t kPostProcessMode_Count = {len(modes)};")
    lines.append("")

    return "\n".join(lines)

def main():
    # Base paths relative to this script
    script_dir = Path(__file__).resolve().parent
    workspace_root = script_dir.parent

    default_header = workspace_root / "project" / "IrufemiEngine" / "Renderer" / "PostProcess" / "PostProcessDefinitions.h"
    default_output = workspace_root / "project" / "IrufemiEngine" / "EngineResources" / "shaders" / "PostProcessModes.generated.hlsli"

    header_path = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else default_header
    output_path = Path(sys.argv[2]).resolve() if len(sys.argv) > 2 else default_output

    print(f"[CodeGen] Parsing: {header_path}")
    modes = parse_post_process_definitions(header_path)
    print(f"[CodeGen] Found {len(modes)} post-process modes.")

    generated_content = generate_hlsl_header(modes)

    # Avoid touching file timestamp if content has not changed (prevents redundant recompiles)
    if output_path.exists():
        existing_content = output_path.read_text(encoding="utf-8")
        if existing_content == generated_content:
            print(f"[CodeGen] {output_path.name} is up to date (no changes).")
            return 0

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(generated_content, encoding="utf-8", newline="\n")
    print(f"[CodeGen] Successfully generated: {output_path}")
    return 0

if __name__ == "__main__":
    sys.exit(main())

